/**
 * The generated agent file behind kimi's `--tools none`.
 *
 * Kimi 0.31.1 has no tool-removal flag, but an agent definition's frontmatter
 * carries the profile's tool allowlist: `tools` accepts a comma-separated
 * string or a list, `["*"]` means unrestricted, and an explicit empty list is
 * the file's own set (embedded `packages/agent-core/src/profile/agentfile/
 * parser.ts` and `from-file.ts` in the 0.31.1 binary; the flag is
 * `--agent-file <path>`, "Load an agent definition from a Markdown file",
 * 0.31.1 `--help`). The profile's tools reach the tool manager verbatim:
 * setActiveTools puts them in a set of enabled exact names plus MCP access
 * patterns, and both gates are strict membership tests, so an empty list
 * enables no built-in and no MCP tool, and get loopTools derives from the
 * same sets (agent/tools ToolManager). A profile renderer even prints the
 * state as "Tools: none", distinct from an unset list's "Tools: all". The
 * manager registers builtins regardless, but registration is not exposure:
 * only loopTools reach the model.
 *
 * An agent file must carry a non-empty prompt body, and that body becomes the
 * profile's system prompt. Codemux therefore writes exactly `${base_prompt}`,
 * which both engines define as the effective default profile's own prompt for
 * an explicit --agent-file (v1 `entryFromDefinition`, v2
 * ExplicitAgentProfileLoaderService), so the run keeps kimi's base
 * instructions, and everything else in the definition is left unset.
 *
 * The file lives under the real brand home in `.codemux/`, a directory no
 * discovery scans (user agents come from `<brand home>/agents` and
 * `~/.agents/agents`, skills from `<brand home>/skills`, embedded `roots.ts`
 * conventions at 0.31.1) and one scode keeps reachable as harness state;
 * never under the temp root, whose Linux sandbox mount would hide it. The
 * capability is claimed and verified live through the provider override:
 * under `--tools none` neither capability probe could produce its secret
 * while a plain run produced both (2026-09-17, re-run 2026-10-04; see
 * docs/isolation.md).
 */

import { randomBytes } from "node:crypto";
import {
  lstatSync,
  mkdirSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { pidProbeAlive } from "./process-table.js";
import {
  assertTrustedParentUnchanged,
  recordTrustedParent,
  removeUnderTrustedParent,
  removeUnderTrustedParentOrThrow,
  reportingHook,
  type TrustedParentRecord,
} from "./safe-remove.js";

export interface KimiNoToolsFile {
  /** The path to pass as `--agent-file`. */
  path: string;
  /** Removes the file. */
  finalize: () => void;
}

const PARENT_DIR_NAME = ".codemux";
const FILE_PREFIX = "no-tools-";

const AGENT_FILE_TEXT = [
  "---",
  "name: codemux-no-tools",
  "description: Tools-free profile generated by codemux; keeps the default prompt.",
  "tools: []",
  "---",
  "",
  "${base_prompt}",
  "",
].join("\n");

// A codemux that died without its exit handler leaves the file behind; it is
// swept only once older than any run could still be reading it.
const STALE_FILE_MS = 2 * 86_400_000;

/** Removes files left behind by codemux processes that no longer exist. */
function sweepStaleFiles(parent: string, record: TrustedParentRecord): void {
  let entries: string[];
  try {
    entries = readdirSync(parent);
  } catch {
    return;
  }
  for (const entry of entries) {
    const match = /^no-tools-(\d+)-/.exec(entry);
    if (!match) continue;
    const pid = Number(match[1]);
    if (pid === process.pid || pidProbeAlive(pid)) continue;
    const path = join(parent, entry);
    // A regular file is the only entry this sweep owns: the no-tools files
    // codemux writes. Anything else carrying the name — a directory planted
    // at one, a symlink — stays with a report, the h4 review's rule: the
    // removal was never recursive, and recursing through
    // removeUnderTrustedParent would not add safety, only a choice about
    // content codemux never created.
    const identity = lstatSync(path, { throwIfNoEntry: false });
    if (identity === undefined) continue;
    if (!identity.isFile()) {
      console.error(
        `codemux: the stale kimi no-tools agent file ${path} is not a regular file; the file was kept`
      );
      continue;
    }
    let age: number;
    try {
      age = Date.now() - statSync(path).mtimeMs;
    } catch {
      continue;
    }
    if (age < STALE_FILE_MS) continue;
    // One bad entry must not block the run, or every later run: the entry
    // stays, the sweep moves on, and the operator learns why (an entry the
    // sweep cannot remove is never cleaned up by retrying it either). The
    // removal revalidates the recorded parent first (src/safe-remove.ts,
    // review round 381): the enumeration and the removals are separate
    // steps, and a parent swapped for a symlink in between must be caught
    // at the removal, never followed through it — the hermetic sweep's
    // rule (review round 292).
    removeUnderTrustedParent(path, record, `the stale kimi no-tools agent file ${path}`);
  }
}

/**
 * Writes the no-tools agent file. `brandHome` is the real kimi brand home
 * (the directory `kimi` reads config.toml, skills and agents from).
 */
export function writeKimiNoToolsFile(brandHome: string): KimiNoToolsFile {
  const parent = join(brandHome, PARENT_DIR_NAME);
  mkdirSync(parent, { recursive: true, mode: 0o700 });
  // Recorded BEFORE the sweep runs, and every removal the sweep makes
  // revalidates the record (src/safe-remove.ts, review round 381): the
  // enumeration and the removals are separate steps, and a kimi child with
  // write access to the brand home could replace `.codemux` with a symlink
  // in between, so a bare rm removed the same-named file wherever the
  // replacement pointed. The record also carries the shape and ownership
  // assertion the old inline lstat made (assertTrustedDirectory), so a bad
  // parent still fails the write itself, and the finalizer revalidates the
  // same record by device and inode (review round 104).
  const parentRecord: TrustedParentRecord = recordTrustedParent(parent);
  sweepStaleFiles(parent, parentRecord);
  // A parent the sweep found swapped kept its entries and reported; this
  // run's own file must not be written through the replacement either
  // (the run-directory parent's rule, review round 295).
  assertTrustedParentUnchanged(parentRecord, "the kimi no-tools parent");
  const path = join(parent, `${FILE_PREFIX}${process.pid}-${randomBytes(6).toString("hex")}.md`);
  // Guarded from the file's creation to its finalizer's registration
  // (review round 123): a write that fails here removes the just-made file
  // through the same revalidated removal the finalizer uses, and the
  // original error reaches the caller instead of an empty or partial file
  // the days-later stale sweep has to reclaim. The parent itself stays —
  // it is the shared, persistent `.codemux` directory every run uses.
  // The create is exclusive, and EEXIST removes nothing: an entry already
  // at the name is not this run's (review round 124).
  try {
    writeFileSync(path, AGENT_FILE_TEXT, { mode: 0o600, flag: "wx" });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST") {
      removeUnderTrustedParent(path, parentRecord, `the kimi no-tools agent file ${path}`);
    }
    throw error;
  }

  let finalized = false;
  const finalize = (): void => {
    if (finalized) return;
    // Thrown when refused or failed, so the adapter's cleanupHome reports
    // the kept file; it stays retryable, and the exit hook retries and
    // reports (review round 104: `finalized` used to be set before the
    // removal, so a transiently failed removal left the file behind with
    // the exit hook already disarmed).
    removeUnderTrustedParentOrThrow(path, parentRecord, `the kimi no-tools agent file ${path}`);
    finalized = true;
    process.off("exit", atExit);
  };
  const atExit = reportingHook(finalize);
  process.once("exit", atExit);

  return { path, finalize };
}
